const CACHE_NAME = 'pratyeksha-feedback-suite-v1';
const APP_SHELL = ['/feedback-suite-app/', '/feedback-suite-app/admin', '/feedback-suite-app/admin/login', '/feedback-suite-app/manifest.webmanifest'];

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE_NAME).then((cache) => cache.addAll(APP_SHELL)));
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((key) => key.startsWith('pratyeksha-feedback-suite-') && key !== CACHE_NAME).map((key) => caches.delete(key))))
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith('/api/')) return;

  event.respondWith(
    fetch(request)
      .then((response) => {
        const copy = response.clone();
        caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
        return response;
      })
      .catch(() => caches.open(CACHE_NAME).then((cache) => cache.match(request).then((cached) => cached || cache.match('/feedback-suite-app/admin'))))
  );
});
